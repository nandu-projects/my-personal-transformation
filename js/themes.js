const LAYOUTS = [
  { id: 'classic', name: 'Classic', description: 'Single-column task cards with large readable layout' },
  { id: 'compact', name: 'Compact', description: 'Smaller cards with more tasks visible on screen' },
  { id: 'dashboard', name: 'Dashboard', description: 'Summary cards in 2 columns, task list single column' },
  { id: 'minimal', name: 'Minimal', description: 'Clean flat cards with minimal borders and distraction' },
  { id: 'focus', name: 'Focus', description: 'Active tasks visually highlighted with reduced noise' }
];

class ThemeManager {
  static getThemes() {
    return THEMES;
  }

  static getLayouts() {
    return LAYOUTS;
  }

  static getTheme(themeId) {
    return THEMES.find(t => t.id === themeId) || THEMES[0];
  }

  static getLayout(layoutId) {
    return LAYOUTS.find(l => l.id === layoutId) || LAYOUTS[0];
  }

  static applyThemeToElement(theme, element) {
    if (!theme || !element) return;
    element.style.setProperty('--color-brand', theme.brand);
    element.style.setProperty('--color-brand-glow', theme.brandGlow || 'rgba(56, 189, 248, 0.2)');
    element.style.setProperty('--color-accent', theme.accent || theme.brand);
    element.style.setProperty('--bg-app', theme.bgApp);
    element.style.setProperty('--bg-surface', theme.bgSurface);
    element.style.setProperty('--bg-card', theme.bgCard);
    element.style.setProperty('--bg-card-hover', theme.bgCardHover);
    element.style.setProperty('--bg-input', theme.bgInput);
    element.style.setProperty('--text-primary', theme.textPrimary);
    element.style.setProperty('--text-secondary', theme.textSecondary);
    element.style.setProperty('--text-muted', theme.textMuted);
    element.style.setProperty('--border-subtle', theme.border);
    element.style.setProperty('--color-success', theme.success);
    element.style.setProperty('--color-warning', theme.warning);
    element.style.setProperty('--color-danger', theme.danger);
    element.style.setProperty('--progress-fill-color', theme.progressBar || theme.brand);

    if (element === document.documentElement) {
      document.documentElement.setAttribute('data-theme', theme.mode);
      document.documentElement.setAttribute('data-theme-id', theme.id);
      
      // Update theme-color meta tag for Android status bar
      const meta = document.querySelector('meta[name="theme-color"]');
      if (meta) meta.setAttribute('content', theme.bgApp);
    }
  }

  static applyLayout(layoutId) {
    const layout = this.getLayout(layoutId);
    document.documentElement.setAttribute('data-layout', layout.id);
  }

  static apply(themeId, layoutId) {
    const theme = this.getTheme(themeId);
    this.applyThemeToElement(theme, document.documentElement);
    if (layoutId) {
      this.applyLayout(layoutId);
    }
  }
}

if (typeof window !== 'undefined') {
  window.THEMES = THEMES;
  window.LAYOUTS = LAYOUTS;
  window.ThemeManager = ThemeManager;
}

if (typeof module !== 'undefined' && module.exports) {
  module.exports = { THEMES, LAYOUTS, ThemeManager };
}
